import type { InnerAudioContext, InnerAudioError, MiniProgramPerformance, RealtimeLogManager } from '@weapp-vite/web'
import * as api from '@weapp-vite/web'
import * as runtime from '@weapp-vite/web/runtime'
import * as polyfill from '@weapp-vite/web/runtime/polyfill'
import { expectError, expectType } from 'tsd'

for (const surface of [api, runtime, polyfill]) {
  expectType<string>(surface.arrayBufferToBase64(new ArrayBuffer(1)))
  expectType<ArrayBuffer>(surface.base64ToArrayBuffer('AA=='))
  expectError(surface.arrayBufferToBase64('AA=='))
  expectError(surface.base64ToArrayBuffer(new ArrayBuffer(1)))
  expectType<MiniProgramPerformance>(surface.getPerformance())
  expectType<RealtimeLogManager>(surface.getRealtimeLogManager())
  expectType<InnerAudioContext>(surface.createInnerAudioContext())
  expectType<InnerAudioContext>(surface.createInnerAudioContext({ useWebAudioImplement: true }))
  expectType<void>(surface.reportMonitor('launch', 1))
  expectError(surface.reportMonitor('launch'))
  expectError(surface.reportMonitor('launch', '1'))
  expectType<Promise<{ errMsg: string }>>(surface.setKeepScreenOn({ keepScreenOn: true }))
  expectType<Promise<{ errMsg: string }>>(surface.setEnableDebug({ enableDebug: true }))
  expectError(surface.setKeepScreenOn({ keepScreenOn: 'yes' }))
  expectError(surface.setEnableDebug({ enableDebug: 1 }))
  expectType<void>(surface.onKeyboardHeightChange(event => expectType<number>(event.height)))
  expectType<void>(surface.offKeyboardHeightChange())
  expectType<void>(surface.onMemoryWarning(event => expectType<5 | 10 | 15>(event.level)))
  expectType<void>(surface.offMemoryWarning())
  expectError(surface.onKeyboardHeightChange())
  expectError(surface.onMemoryWarning())
}

const performance = api.getPerformance()
expectType<void>(performance.setBufferSize(30))
expectError(performance.now())
expectError(performance.createObserver())
const observer = performance.createObserver(() => {})
expectType<void>(observer.observe({ type: 'render' }))
expectType<void>(observer.disconnect())
expectError(observer.observe({ type: 'browser-timing' }))

const logger = api.getRealtimeLogManager()
expectType<void>(logger.info('value', { count: 1 }))
expectType<void>(logger.error('failure'))
expectType<void>(logger.setFilterMsg('launch'))
expectType<void>(logger.addFilterMsg('ready'))
expectType<void>(logger.in({}))
expectType<void>(logger.tag('network').warn('request', { code: 500 }))
expectType<number>(logger.getCurrentState().logCount)
expectError(logger.tag())

const audio = api.createInnerAudioContext()
expectType<void>(audio.play())
expectType<void>(audio.pause())
expectType<void>(audio.stop())
expectType<void>(audio.seek(1))
expectType<void>(audio.destroy())
expectType<void>(audio.onError(event => expectType<InnerAudioError>(event)))
expectType<void>(audio.offError())
expectType<void>(audio.onSeeked(() => {}))
expectType<void>(audio.offSeeked())
expectType<number>(audio.duration)
expectType<number>(audio.buffered)
expectType<boolean>(audio.paused)
expectError(audio.duration = 1)
expectError(audio.paused = true)
expectError(audio.src = 1)
expectError(audio.seek('1'))
expectError(audio.onPlay())
