import type { Server } from 'node:http'
import { EventEmitter } from 'node:events'
import { expect, it, vi } from 'vitest'
import { observeHost } from './host'

it('observes the original connection/request/close without reading headers/body/query and disposes every listener', () => {
  const server = Object.assign(new EventEmitter(), { address: () => ({ address: '127.0.0.1', port: 0 }) })
  const socket = Object.assign(new EventEmitter(), { localPort: 0, remotePort: 0 })
  const request = Object.assign(new EventEmitter(), { socket, method: 'GET', url: '/dimina/?token=private' })
  const response = Object.assign(new EventEmitter(), { statusCode: 200 })
  const readHeaders = vi.fn(() => {
    throw new Error('headers must not be read')
  })
  const readBody = vi.fn(() => {
    throw new Error('body must not be read')
  })
  Object.defineProperties(request, { headers: { get: readHeaders }, body: { get: readBody } })
  const app = vi.fn()
  server.on('request', app)
  const record = vi.fn()
  const dispose = observeHost(server as unknown as Server, record)
  server.emit('listening')
  server.emit('connection', socket)
  server.emit('request', request, response)
  response.emit('finish')
  socket.emit('close', false)
  server.emit('close')
  expect(app).toHaveBeenCalledOnce()
  expect(readHeaders).not.toHaveBeenCalled()
  expect(readBody).not.toHaveBeenCalled()
  expect(record.mock.calls.map(([event]) => event.event)).toEqual(['listening', 'connection', 'request', 'response-finish', 'connection-close', 'server-close'])
  expect(record).toHaveBeenCalledWith({ event: 'request', socketId: 1, method: 'GET', pathname: '/dimina/' })
  expect(JSON.stringify(record.mock.calls)).not.toContain('private')
  dispose()
  dispose()
  expect(server.listenerCount('request')).toBe(1)
  expect(server.listenerCount('listening')).toBe(0)
  expect(server.listenerCount('connection')).toBe(0)
  expect(server.listenerCount('close')).toBe(0)
  expect(socket.listenerCount('close')).toBe(0)
  expect(request.listenerCount('aborted')).toBe(0)
  expect(response.listenerCount('finish')).toBe(0)
  expect(response.listenerCount('close')).toBe(0)
})

it('removes still-pending socket and request/response observers without closing application resources', () => {
  const server = Object.assign(new EventEmitter(), { address: () => null })
  const socket = new EventEmitter()
  const request = Object.assign(new EventEmitter(), { socket, method: 'GET', url: '/' })
  const response = Object.assign(new EventEmitter(), { statusCode: 200 })
  const applicationClose = vi.fn()
  socket.on('close', applicationClose)
  const record = vi.fn()
  const dispose = observeHost(server as unknown as Server, record)
  server.emit('connection', socket)
  server.emit('request', request, response)
  dispose()
  expect(socket.listenerCount('close')).toBe(1)
  expect(request.listenerCount('aborted')).toBe(0)
  expect(response.listenerCount('finish')).toBe(0)
  expect(response.listenerCount('close')).toBe(0)
  expect(applicationClose).not.toHaveBeenCalled()
  record.mockClear()
  socket.emit('close', false)
  response.emit('finish')
  expect(record).not.toHaveBeenCalled()
  expect(applicationClose).toHaveBeenCalledOnce()
})
